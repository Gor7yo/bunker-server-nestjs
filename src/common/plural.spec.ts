import { PLAYERS, plural } from './plural';

describe('plural', () => {
  it.each([
    [1, 'игрок'],
    [2, 'игрока'],
    [4, 'игрока'],
    [5, 'игроков'],
    [11, 'игроков'],
    [12, 'игроков'],
    [14, 'игроков'],
    [21, 'игрок'],
    [22, 'игрока'],
    [111, 'игроков'],
    [0, 'игроков'],
  ])('%i → %s', (n, word) => {
    expect(plural(n, PLAYERS)).toBe(word);
  });
});
